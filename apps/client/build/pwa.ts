import { createHash } from 'node:crypto';
import type { Plugin } from 'vite';
import { generateIcons } from './icons';

/**
 * Tiny dependency-free PWA plugin:
 *  - generates icons (pixel art → PNG) and manifest.webmanifest,
 *  - emits sw.js that precaches the whole build (offline solo play) with a content-hash cache name.
 * In dev it serves the icons/manifest from memory and does not register a service worker.
 */
const manifest = {
  name: 'Afterlife Overdrive',
  short_name: 'Afterlife',
  description: 'Пиксельная кооперативная roguelite: смерть — только начало.',
  lang: 'ru',
  start_url: '/',
  scope: '/',
  display: 'fullscreen',
  display_override: ['fullscreen', 'standalone'],
  orientation: 'landscape',
  background_color: '#0d0a12',
  theme_color: '#0d0a12',
  icons: [
    { src: '/icons/icon-192.png', sizes: '192x192', type: 'image/png' },
    { src: '/icons/icon-512.png', sizes: '512x512', type: 'image/png' },
    {
      src: '/icons/icon-maskable-512.png',
      sizes: '512x512',
      type: 'image/png',
      purpose: 'maskable',
    },
  ],
};

function swSource(cacheName: string, precache: string[]): string {
  return `// Generated by apps/client/build/pwa.ts — do not edit.
const CACHE = ${JSON.stringify(cacheName)};
const PRECACHE = ${JSON.stringify(precache)};

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(CACHE).then((c) => c.addAll(PRECACHE)));
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    (async () => {
      for (const key of await caches.keys()) {
        if (key !== CACHE && key.startsWith('ao-')) await caches.delete(key);
      }
      await self.clients.claim();
    })(),
  );
});

self.addEventListener('message', (event) => {
  if (event.data === 'skipWaiting') self.skipWaiting();
});

self.addEventListener('fetch', (event) => {
  const req = event.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);
  if (url.origin !== self.location.origin || url.pathname.startsWith('/api/')) return;
  if (req.mode === 'navigate') {
    // Network first so a new deploy is picked up; offline falls back to the cached shell.
    event.respondWith(
      fetch(req).catch(async () => (await caches.match('/', { cacheName: CACHE })) || Response.error()),
    );
    return;
  }
  event.respondWith(
    caches.match(req, { cacheName: CACHE }).then((hit) => hit || fetch(req)),
  );
});
`;
}

export function pwaPlugin(): Plugin {
  const icons = generateIcons();
  return {
    name: 'ao-pwa',
    configureServer(server) {
      server.middlewares.use((req, res, next) => {
        const path = (req.url ?? '').split('?')[0]!.replace(/^\//, '');
        if (path === 'manifest.webmanifest') {
          res.setHeader('Content-Type', 'application/manifest+json');
          res.end(JSON.stringify(manifest));
          return;
        }
        const icon = icons[path];
        if (icon) {
          res.setHeader('Content-Type', 'image/png');
          res.end(icon);
          return;
        }
        next();
      });
    },
    generateBundle(_opts, bundle) {
      for (const [fileName, source] of Object.entries(icons)) {
        this.emitFile({ type: 'asset', fileName, source });
      }
      this.emitFile({
        type: 'asset',
        fileName: 'manifest.webmanifest',
        source: JSON.stringify(manifest, null, 2),
      });
      const files = Object.keys(bundle)
        .filter((f) => !f.endsWith('.map') && !f.startsWith('.vite/') && !f.endsWith('.woff'))
        .filter((f) => !/-(vietnamese|greek|greek-ext)-/.test(f));
      const precache = [
        '/',
        '/manifest.webmanifest',
        ...Object.keys(icons).map((f) => '/' + f),
        ...files.filter((f) => f !== 'index.html').map((f) => '/' + f),
      ];
      const hash = createHash('sha256').update(precache.join('\n'));
      for (const f of files) {
        const item = bundle[f]!;
        hash.update(item.type === 'chunk' ? item.code : String(item.source.length));
      }
      this.emitFile({
        type: 'asset',
        fileName: 'sw.js',
        source: swSource('ao-' + hash.digest('hex').slice(0, 12), precache),
      });
    },
  };
}
