export interface Appearance {
  gender: 'm' | 'f';
  skin: number;
  hairStyle: HairStyle;
  hairColor: number;
  eyeColor: number;
  clothColor: number;
  pantsColor: number;
}

export const DEFAULT_APPEARANCE: Appearance = {
  gender: 'm',
  skin: 1,
  hairStyle: 'short',
  hairColor: 1,
  eyeColor: 1,
  clothColor: 1,
  pantsColor: 7,
};

/** What the equipped armor looks like (from item content). */
export interface EquipLook {
  helmet?: { shape: string; material: string };
  chest?: { shape: string; material: string };
  boots?: { material: string };
}

function pick(list: readonly string[], i: number): string {
  return list[((i % list.length) + list.length) % list.length]!;
}

export function appearanceSlots(a: Appearance, look: EquipLook = {}): SlotColors {
  const skin = pick(SKIN_TONES, a.skin);
  const hair = pick(HAIR_COLORS, a.hairColor);
  const cloth = pick(CLOTH_COLORS, a.clothColor);
  const pants = pick(CLOTH_COLORS, a.pantsColor);
  const boots = look.boots ? MATERIALS[look.boots.material] : undefined;
  return {
    skin,
    skin2: shade(skin, 0.82),
    hair,
    hair2: shade(hair, 0.72),
    eye: pick(EYE_COLORS, a.eyeColor),
    cloth,
    cloth2: shade(cloth, 0.75),
    pants,
    pants2: shade(pants, 0.75),
    boot: boots ? boots[1] : C.wood1,
    boot2: boots ? boots[0] : C.wood0,
  };
}

export const CHAR_ANIMS = {
  idle: [0, 1],
  run: [2, 3, 4, 5],
} as const;

/** Total composed frames: idle×2, run×4. */
export const CHAR_FRAME_COUNT = 6;

/**
 * Compose the paper-doll into final frames (outlined RGBA, 16×24 each).
 * Frame order matches CHAR_ANIMS. Bob: idle frame 1 and run passing frames lift the body 1px.
 */
export function composeCharacter(a: Appearance, look: EquipLook = {}): RgbaImage[] {
  const slots = appearanceSlots(a, look);
  const helm = look.helmet ? helmetLayers[look.helmet.shape] : undefined;
  const chest = look.chest ? chestLayers[look.chest.shape] : undefined;
  const helmSlots = look.helmet ? materialSlots(look.helmet.material) : undefined;
  const chestSlots = look.chest ? materialSlots(look.chest.material) : undefined;
  const hair = a.hairStyle === 'bald' ? undefined : hairLayers[a.hairStyle];

  const frames: RgbaImage[] = [];
  const plan: { leg: number; bob: number }[] = [
    { leg: 0, bob: 0 },
    { leg: 0, bob: 1 },
    { leg: 1, bob: 0 },
    { leg: 2, bob: -1 },
    { leg: 3, bob: 0 },
    { leg: 4, bob: -1 },
  ];
  for (const step of plan) {
    const img = createImage(CHAR_W, CHAR_H);
    const by = step.bob;
    blitSprite(img, legsLayer, step.leg, 0, 0, slots);
    blitSprite(img, a.gender === 'f' ? torsoF : torsoM, 0, 0, by, slots);
    if (chest) blitSprite(img, chest, 0, 0, by, chestSlots);
    blitSprite(img, headLayer, 0, 0, by, slots);
    blitSprite(img, a.gender === 'f' ? eyesLayerF : eyesLayerM, 0, 0, by, slots);
    if (hair && !(helm && helm.hidesHair)) blitSprite(img, hair, 0, 0, by, slots);
    if (helm) blitSprite(img, helm.def, 0, 0, by, helmSlots);
    frames.push(outline(img, C.ink));
  }
  return frames;
}

export function materialSlots(material: string): SlotColors {
  const m = MATERIALS[material] ?? MATERIALS.iron!;
  return { m0: m[0], m1: m[1], m2: m[2] };
}

